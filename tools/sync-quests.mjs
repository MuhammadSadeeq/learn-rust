#!/usr/bin/env node
// Reads quests/quests.toml and regenerates:
//   * quests/Cargo.toml          (one [[bin]] per single-file quest, so rust-analyzer sees every file)
//   * site/assets/quests-data.js (quest list for the website)
// Run after editing quests.toml:  node tools/sync-quests.mjs
//
// Cargo quests (kind = "cargo") are small packages under quests/pkgs/. They
// are not bins here: each package has its own manifest and workspace.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseQuests } from "./sync-quests-lib.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const KINDS = new Set(["std", "cargo"]);
const kindOf = (q) => q.kind ?? "std";

const quests = parseQuests(fs.readFileSync(path.join(ROOT, "quests/quests.toml"), "utf8"));
const names = new Set();
for (const q of quests) {
  for (const k of ["name", "chapter", "path", "title"]) if (q[k] === undefined) throw new Error(`quest ${JSON.stringify(q)} is missing ${k}`);
  if (names.has(q.name)) throw new Error(`duplicate quest name ${q.name}`);
  if (!KINDS.has(kindOf(q))) throw new Error(`quest ${q.name} has unknown kind ${q.kind}`);
  names.add(q.name);
}

let cargo = `# GENERATED by tools/sync-quests.mjs from quests.toml. Do not edit by hand.
# Every quest is its own binary, so a broken quest never stops the others
# from compiling, and your editor (rust-analyzer) checks each file live.
[package]
name = "quests"
version = "0.1.0"
edition = "2024"
publish = false
autobins = false
autoexamples = false
autotests = false
autobenches = false

[lints.rust]
dead_code = "allow"
unused_variables = "allow"
unused_mut = "allow"
unused_imports = "allow"
`;
for (const q of quests.filter((q) => kindOf(q) === "std")) cargo += `\n[[bin]]\nname = "${q.name}"\npath = "${q.path}"\n`;
fs.writeFileSync(path.join(ROOT, "quests/Cargo.toml"), cargo);

// How many tests a quest has: its #[test] and #[tokio::test] attributes, in
// the quest's own files (for a cargo quest, src/ and tests/). The website uses
// it as the boss's hit points. 0 when the files are missing.
const TEST_ATTR = /^\s*#\[(?:tokio::)?test\b/;
const rsFiles = (dir) => {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) return rsFiles(p);
    return entry.name.endsWith(".rs") ? [p] : [];
  });
};
const countTests = (q) => {
  const base = path.join(ROOT, "quests", q.path);
  const files = kindOf(q) === "std" ? [base] : [...rsFiles(path.join(base, "src")), ...rsFiles(path.join(base, "tests"))];
  return files
    .filter((file) => fs.existsSync(file))
    .reduce((n, file) => n + fs.readFileSync(file, "utf8").split(/\r?\n/).filter((line) => TEST_ATTR.test(line)).length, 0);
};

const web = quests.map((q) => ({
  name: q.name,
  chapter: q.chapter,
  path: q.path,
  title: q.title,
  summary: q.summary,
  boss: !!q.boss,
  kind: kindOf(q),
  tests: countTests(q),
}));
fs.writeFileSync(
  path.join(ROOT, "site/assets/quests-data.js"),
  `/* GENERATED by tools/sync-quests.mjs from quests/quests.toml. Do not edit by hand. */\nwindow.OX_QUESTS = ${JSON.stringify(web, null, 1)};\n`
);
const missing = quests.filter((q) => !fs.existsSync(path.join(ROOT, "quests", q.path)));
console.log(`${quests.length} quests synced.${missing.length ? ` ${missing.length} quest files not written yet.` : ""}`);
